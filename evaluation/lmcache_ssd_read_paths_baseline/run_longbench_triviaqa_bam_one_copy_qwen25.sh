#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
TIMESTAMP="$(date +%Y%m%d_%H%M%S)"

# LongBench-TriviaQA 版本的 BaM one-copy baseline。
#
# 这条链路用于和同目录下的 LMCache SSD/GDS LongBench baseline 对比：
#
#   request_1:
#     vLLM prefill -> LMCache chunk -> shadow write 到 BaM
#
#   request_2:
#     LMCache prefer-load 命中同一 prompt
#       -> BaM KV fast path
#       -> GPU persistent service poll/read
#       -> mover CTA one-copy scatter 到 vLLM paged KV cache
#
# 注意：
# 这里不调用固定 prompt 的主启动脚本，因此必须显式设置 one-copy 所需的底层
# runtime/persistent/mover 开关，避免出现“只设置 branch 名但实际没有启动
# persistent service”的半配置状态。

MANIFEST_PATH_VALUE="${MANIFEST_PATH:-/home/xhk/llm-inference/datasets/longbench/organized/triviaqa/full/buckets/lt4k.jsonl}"
MODEL_PATH_VALUE="${MODEL_PATH:-/home/xhk/llm-inference/models/Qwen2.5-7B-Instruct}"
PYTHON_BIN_VALUE="${PYTHON_BIN:-/home/xhk/miniconda3/envs/pytorch-vllm/bin/python}"
LMCACHE_REPO_PATH_VALUE="${LMCACHE_REPO_PATH:-/home/xhk/llm-inference/LMCache-v0-torch26}"

LOG_ROOT_VALUE="${LOG_ROOT:-${SCRIPT_DIR}/logs_longbench_triviaqa/bam_one_copy}"
RUN_DIR_VALUE="${RUN_DIR:-${LOG_ROOT_VALUE}/${TIMESTAMP}}"
LOG_FILE_VALUE="${LOG_FILE:-${RUN_DIR_VALUE}/run.log}"
METRICS_JSONL_VALUE="${METRICS_JSONL:-${RUN_DIR_VALUE}/metrics.jsonl}"
TEST_ROOT_VALUE="${LMCACHE_SSD_TEST_ROOT:-${RUN_DIR_VALUE}}"

LMCACHE_LOCAL_DISK_VALUE="${LMCACHE_LOCAL_DISK:-${TEST_ROOT_VALUE}/lmcache_local_disk/}"

MAX_MODEL_LEN_VALUE="${MAX_MODEL_LEN:-4096}"
GPU_MEMORY_UTILIZATION_VALUE="${GPU_MEMORY_UTILIZATION:-0.60}"
MAX_TOKENS_VALUE="${MAX_TOKENS:-32}"
NUM_SAMPLES_VALUE="${NUM_SAMPLES:-4}"
REPEAT_READ_VALUE="${REPEAT_READ:-1}"
DTYPE_VALUE="${DTYPE:-half}"
ENFORCE_EAGER_VALUE="${ENFORCE_EAGER:-true}"
ENABLE_CHUNKED_PREFILL_VALUE="${ENABLE_CHUNKED_PREFILL:-false}"

VLLM_BAM_IMPORT_PATH_VALUE="${VLLM_BAM_IMPORT_PATH:-/home/xhk/llm-inference/BaM_IOStack/gids_module}"
BAM_LIB_DIR_VALUE="${BAM_LIB_DIR:-/home/xhk/llm-inference/BaM_IOStack/bam/build/lib}"
VLLM_BAM_CACHE_SIZE_MB_VALUE="${VLLM_BAM_CACHE_SIZE_MB:-1024}"
VLLM_BAM_NUM_SSD_VALUE="${VLLM_BAM_NUM_SSD:-1}"
VLLM_BAM_SSD_LIST_VALUE="${VLLM_BAM_SSD_LIST:-0}"
VLLM_BAM_CTRL_IDX_VALUE="${VLLM_BAM_CTRL_IDX:-0}"
VLLM_BAM_CACHE_STATS_EVERY_ITER_VALUE="${VLLM_BAM_CACHE_STATS_EVERY_ITER:-1}"
GIDS_FORCE_SYNC_READ_VALUE="${GIDS_FORCE_SYNC_READ:-1}"
GIDS_KV_DEBUG_VALUE="${GIDS_KV_DEBUG:-0}"
GIDS_KV_WAIT_TIMEOUT_S_VALUE="${GIDS_KV_WAIT_TIMEOUT_S:-10}"
GIDS_KV_GPU_WORKER_MOVER_CTAS_VALUE="${GIDS_KV_GPU_WORKER_MOVER_CTAS:-4}"

mkdir -p "${RUN_DIR_VALUE}"
mkdir -p "${LMCACHE_LOCAL_DISK_VALUE}"

# BaM 设备路径通常需要 root 权限；固定 prompt 主脚本也会在 BaM 打开时自动
# sudo。这里保持同样语义，并只透传本脚本需要的变量。
if [[ "${EUID}" -ne 0 ]]; then
  exec sudo env \
    "MANIFEST_PATH=${MANIFEST_PATH_VALUE}" \
    "MODEL_PATH=${MODEL_PATH_VALUE}" \
    "PYTHON_BIN=${PYTHON_BIN_VALUE}" \
    "LMCACHE_REPO_PATH=${LMCACHE_REPO_PATH_VALUE}" \
    "LOG_ROOT=${LOG_ROOT_VALUE}" \
    "RUN_DIR=${RUN_DIR_VALUE}" \
    "LOG_FILE=${LOG_FILE_VALUE}" \
    "METRICS_JSONL=${METRICS_JSONL_VALUE}" \
    "LMCACHE_SSD_TEST_ROOT=${TEST_ROOT_VALUE}" \
    "LMCACHE_LOCAL_DISK=${LMCACHE_LOCAL_DISK_VALUE}" \
    "MAX_MODEL_LEN=${MAX_MODEL_LEN_VALUE}" \
    "GPU_MEMORY_UTILIZATION=${GPU_MEMORY_UTILIZATION_VALUE}" \
    "MAX_TOKENS=${MAX_TOKENS_VALUE}" \
    "NUM_SAMPLES=${NUM_SAMPLES_VALUE}" \
    "REPEAT_READ=${REPEAT_READ_VALUE}" \
    "DTYPE=${DTYPE_VALUE}" \
    "ENFORCE_EAGER=${ENFORCE_EAGER_VALUE}" \
    "ENABLE_CHUNKED_PREFILL=${ENABLE_CHUNKED_PREFILL_VALUE}" \
    "CUDA_DEVICE=${CUDA_DEVICE:-0}" \
    "LMCACHE_USE_EXPERIMENTAL=${LMCACHE_USE_EXPERIMENTAL:-True}" \
    "LMCACHE_CHUNK_SIZE=${LMCACHE_CHUNK_SIZE:-256}" \
    "LMCACHE_LOCAL_CPU=${LMCACHE_LOCAL_CPU:-False}" \
    "LMCACHE_MAX_LOCAL_CPU_SIZE=${LMCACHE_MAX_LOCAL_CPU_SIZE:-5.0}" \
    "LMCACHE_MAX_LOCAL_DISK_SIZE=${LMCACHE_MAX_LOCAL_DISK_SIZE:-20}" \
    "VLLM_BAM_IMPORT_PATH=${VLLM_BAM_IMPORT_PATH_VALUE}" \
    "BAM_LIB_DIR=${BAM_LIB_DIR_VALUE}" \
    "VLLM_BAM_CACHE_SIZE_MB=${VLLM_BAM_CACHE_SIZE_MB_VALUE}" \
    "VLLM_BAM_NUM_SSD=${VLLM_BAM_NUM_SSD_VALUE}" \
    "VLLM_BAM_SSD_LIST=${VLLM_BAM_SSD_LIST_VALUE}" \
    "VLLM_BAM_CTRL_IDX=${VLLM_BAM_CTRL_IDX_VALUE}" \
    "VLLM_BAM_CACHE_STATS_EVERY_ITER=${VLLM_BAM_CACHE_STATS_EVERY_ITER_VALUE}" \
    "GIDS_FORCE_SYNC_READ=${GIDS_FORCE_SYNC_READ_VALUE}" \
    "GIDS_KV_DEBUG=${GIDS_KV_DEBUG_VALUE}" \
    "GIDS_KV_WAIT_TIMEOUT_S=${GIDS_KV_WAIT_TIMEOUT_S_VALUE}" \
    "GIDS_KV_GPU_WORKER_MOVER_CTAS=${GIDS_KV_GPU_WORKER_MOVER_CTAS_VALUE}" \
    "PYTHONPATH=${PYTHONPATH:-}" \
    "LD_LIBRARY_PATH=${BAM_LIB_DIR_VALUE}:${LD_LIBRARY_PATH:-}" \
    bash "$0" "$@"
fi

echo "[longbench-triviaqa-bam-one-copy] manifest=${MANIFEST_PATH_VALUE}"
echo "[longbench-triviaqa-bam-one-copy] run_dir=${RUN_DIR_VALUE}"
echo "[longbench-triviaqa-bam-one-copy] log_file=${LOG_FILE_VALUE}"
echo "[longbench-triviaqa-bam-one-copy] metrics_jsonl=${METRICS_JSONL_VALUE}"
echo "[longbench-triviaqa-bam-one-copy] lmcache_local_disk=${LMCACHE_LOCAL_DISK_VALUE}"
echo "[longbench-triviaqa-bam-one-copy] mover_ctas=${GIDS_KV_GPU_WORKER_MOVER_CTAS_VALUE}"

export CUDA_VISIBLE_DEVICES="${CUDA_DEVICE:-0}"
export VLLM_USE_V1=0
export PYTHONPATH="${LMCACHE_REPO_PATH_VALUE}:${PYTHONPATH:-}"
export LD_LIBRARY_PATH="${BAM_LIB_DIR_VALUE}:${LD_LIBRARY_PATH:-}"
export LMCACHE_USE_EXPERIMENTAL="${LMCACHE_USE_EXPERIMENTAL:-True}"
export LMCACHE_CHUNK_SIZE="${LMCACHE_CHUNK_SIZE:-256}"
export LMCACHE_LOCAL_CPU="${LMCACHE_LOCAL_CPU:-False}"
export LMCACHE_MAX_LOCAL_CPU_SIZE="${LMCACHE_MAX_LOCAL_CPU_SIZE:-5.0}"
export LMCACHE_LOCAL_DISK="${LMCACHE_LOCAL_DISK_VALUE}"
export LMCACHE_MAX_LOCAL_DISK_SIZE="${LMCACHE_MAX_LOCAL_DISK_SIZE:-20}"

# 当前 cta=4 one-copy 稳定基线所需的 BaM/LMCache 环境。
export VLLM_BAM_LMCACHE_SHADOW_ENABLE=1
export VLLM_BAM_LMCACHE_PREFER_LOAD_ENABLE=1
export VLLM_BAM_LMCACHE_SHADOW_CHUNKS="${VLLM_BAM_LMCACHE_SHADOW_CHUNKS:-1024}"
export VLLM_BAM_LMCACHE_READ_MODE="${VLLM_BAM_LMCACHE_READ_MODE:-prefetch}"
export VLLM_BAM_KV_FAST_PATH=1
export VLLM_BAM_KV_BRANCH=gpu_worker_persistent_one_copy
export VLLM_BAM_KV_EXECUTOR=gpu_worker
export VLLM_BAM_DIRECT_PLACEMENT=1
export VLLM_BAM_DIRECT_PLACEMENT_IMPL="${VLLM_BAM_DIRECT_PLACEMENT_IMPL:-fused}"
export VLLM_BAM_DIRECT_PLACEMENT_RUNTIME_ONE_COPY=1
export VLLM_BAM_DIRECT_PLACEMENT_REQUIRE_RUNTIME_ONE_COPY=1
export VLLM_BAM_DIRECT_PLACEMENT_DEFER_RUNTIME=1
export VLLM_BAM_DIRECT_PLACEMENT_DEFER_MIN_POLLS=0
export VLLM_BAM_XFORMERS_PREFIX_FALLBACK_PROFILE="${VLLM_BAM_XFORMERS_PREFIX_FALLBACK_PROFILE:-0}"
export VLLM_BAM_XFORMERS_PREFIX_BACKEND="${VLLM_BAM_XFORMERS_PREFIX_BACKEND:-auto}"
export VLLM_BAM_XFORMERS_QUERY_BACKEND="${VLLM_BAM_XFORMERS_QUERY_BACKEND:-auto}"
export VLLM_BAM_IMPORT_PATH="${VLLM_BAM_IMPORT_PATH_VALUE}"
export VLLM_BAM_CACHE_SIZE_MB="${VLLM_BAM_CACHE_SIZE_MB_VALUE}"
export VLLM_BAM_NUM_SSD="${VLLM_BAM_NUM_SSD_VALUE}"
export VLLM_BAM_SSD_LIST="${VLLM_BAM_SSD_LIST_VALUE}"
export VLLM_BAM_CTRL_IDX="${VLLM_BAM_CTRL_IDX_VALUE}"
export VLLM_BAM_CACHE_STATS_EVERY_ITER="${VLLM_BAM_CACHE_STATS_EVERY_ITER_VALUE}"
export GIDS_FORCE_SYNC_READ="${GIDS_FORCE_SYNC_READ_VALUE}"
export GIDS_KV_DEBUG="${GIDS_KV_DEBUG_VALUE}"
export GIDS_KV_WAIT_TIMEOUT_S="${GIDS_KV_WAIT_TIMEOUT_S_VALUE}"
export GIDS_KV_GPU_WORKER_RUNTIME_ENABLE=1
export GIDS_KV_GPU_WORKER_PERSISTENT_ENABLE=1
export GIDS_KV_GPU_WORKER_MOVER_CTAS="${GIDS_KV_GPU_WORKER_MOVER_CTAS_VALUE}"

# 确保 GDS wrapper 不干扰 BaM one-copy 对照。
export VLLM_GDS_LMCACHE_SHADOW_ENABLE=0
export VLLM_GDS_LMCACHE_PREFER_LOAD_ENABLE=0

cd "${SCRIPT_DIR}/../.."

RUNNER_ARGS=(
  "${SCRIPT_DIR}/longbench_triviaqa_runner.py"
  --manifest "${MANIFEST_PATH_VALUE}"
  --metrics-jsonl "${METRICS_JSONL_VALUE}"
  --model "${MODEL_PATH_VALUE}"
  --max-model-len "${MAX_MODEL_LEN_VALUE}"
  --gpu-memory-utilization "${GPU_MEMORY_UTILIZATION_VALUE}"
  --dtype "${DTYPE_VALUE}"
  --max-tokens "${MAX_TOKENS_VALUE}"
  --num-samples "${NUM_SAMPLES_VALUE}"
  --repeat-read "${REPEAT_READ_VALUE}"
)

if [[ "${ENFORCE_EAGER_VALUE}" == "true" ]]; then
  RUNNER_ARGS+=(--enforce-eager)
else
  RUNNER_ARGS+=(--no-enforce-eager)
fi

if [[ "${ENABLE_CHUNKED_PREFILL_VALUE}" == "true" ]]; then
  RUNNER_ARGS+=(--enable-chunked-prefill)
else
  RUNNER_ARGS+=(--no-enable-chunked-prefill)
fi

"${PYTHON_BIN_VALUE}" "${RUNNER_ARGS[@]}" 2>&1 | tee "${LOG_FILE_VALUE}"
