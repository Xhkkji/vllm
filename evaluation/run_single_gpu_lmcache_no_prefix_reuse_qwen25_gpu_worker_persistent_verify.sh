#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# 这个脚本服务“runtime one-copy + persistent service 主线”的快速验证。
#
# 它复用已有的 GPU worker + persistent 主线包装脚本，并默认强制打开：
# 1. VLLM_BAM_DIRECT_PLACEMENT_RUNTIME_ONE_COPY=1
# 2. VLLM_BAM_DIRECT_PLACEMENT_REQUIRE_RUNTIME_ONE_COPY=1
#
# 这样可以避免调试时误跑回 materialized correctness fallback。
#
# 注意：重型 correctness 诊断默认关闭。
#
# 之前这里默认打开过两项诊断：
# 1. VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE=1
#    在 request finalize 后，把 GPU 最终写入的 KV cache 内容和
#    live request pages 还原出的期望 chunk tensor 做对照。
# 2. VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_ALLOW_LIVE_REFILL=1
#    允许 runtime one-copy 主线在调试模式下复用 live request pages 构造
#    expected tensor；这一步只用于排查，不是正式 steady-state 主线。
#
# 这两项会在 consume 后重新走 live request pages decode/materialized refill，
# 容易和常驻 service 争用 GPU，并把主路径已经完成的 run 卡在调试校验阶段。
# 因此这里默认关闭；需要定位写入正确性时，再用环境变量显式打开。
#
# correctness 排查脚本默认关闭隐藏 prewarm：
# - 主 benchmark 脚本为了 steady-state 默认会在 request 1 后额外跑一次隐藏
#   direct retrieve；
# - 但当前我们要定位 request 2 输出错误，隐藏 prewarm 会额外引入一次
#   request-handle / slot_mapping / scheduler 状态变化；
# - 因此这里默认 `DIRECT_RETRIEVE_PREWARM_AFTER_REQUEST1=0`，让日志里只保留
#   request 1 和真正打印的 request 2，避免把问题边界搅浑。

DIRECT_RETRIEVE_PREWARM_AFTER_REQUEST1="${DIRECT_RETRIEVE_PREWARM_AFTER_REQUEST1:-0}" \
VLLM_BAM_DIRECT_PLACEMENT_RUNTIME_ONE_COPY="${VLLM_BAM_DIRECT_PLACEMENT_RUNTIME_ONE_COPY:-1}" \
VLLM_BAM_DIRECT_PLACEMENT_REQUIRE_RUNTIME_ONE_COPY="${VLLM_BAM_DIRECT_PLACEMENT_REQUIRE_RUNTIME_ONE_COPY:-1}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE:-0}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_ALLOW_LIVE_REFILL="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_ALLOW_LIVE_REFILL:-0}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_SAMPLE_TOKENS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_SAMPLE_TOKENS:-2}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_SAMPLE_DIMS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_SAMPLE_DIMS:-8}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_FULL_COMPARE="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_RUNTIME_WRITE_FULL_COMPARE:-0}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE:-0}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_MAX_CHUNKS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_MAX_CHUNKS:-4}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_MAX_LAYERS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_MAX_LAYERS:-28}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_TOKENS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_TOKENS:-8}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_HEADS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_HEADS:-2}" \
VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_DIMS="${VLLM_BAM_DIRECT_PLACEMENT_VERIFY_OFFICIAL_WRITE_SAMPLE_DIMS:-8}" \
VLLM_BAM_WRITE_READ_VERIFY="${VLLM_BAM_WRITE_READ_VERIFY:-0}" \
VLLM_BAM_WRITE_READ_VERIFY_SYNC_COMPARE="${VLLM_BAM_WRITE_READ_VERIFY_SYNC_COMPARE:-0}" \
VLLM_BAM_DIRECT_RETRIEVE_CROSS_SOURCE_FULL_COMPARE="${VLLM_BAM_DIRECT_RETRIEVE_CROSS_SOURCE_FULL_COMPARE:-0}" \
VLLM_BAM_XFORMERS_PREFIX_BACKEND="${VLLM_BAM_XFORMERS_PREFIX_BACKEND:-auto}" \
VLLM_BAM_XFORMERS_QUERY_BACKEND="${VLLM_BAM_XFORMERS_QUERY_BACKEND:-auto}" \
VLLM_BAM_XFORMERS_VERIFY_PREFIX_GATHER="${VLLM_BAM_XFORMERS_VERIFY_PREFIX_GATHER:-0}" \
VLLM_BAM_XFORMERS_VERIFY_ATTENTION_OUTPUT="${VLLM_BAM_XFORMERS_VERIFY_ATTENTION_OUTPUT:-0}" \
LMCACHE_BAM_REBUILD_SEMANTIC_DEBUG="${LMCACHE_BAM_REBUILD_SEMANTIC_DEBUG:-0}" \
bash "${SCRIPT_DIR}/run_single_gpu_lmcache_no_prefix_reuse_qwen25_gpu_worker_persistent.sh"
